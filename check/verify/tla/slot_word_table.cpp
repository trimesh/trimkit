// Writes SlotWordTable.tla: each transition of src/parallel.hpp's SlotWord,
// computed by the C++ itself, over every small word its precondition allows
// (the ones the C++'s checked() asserts), so the model's slot word moves
// exactly as the code's does. `uv run scripts model` builds and runs this
// before each run of TLC, so the table can't drift from the header
#include "../../../src/parallel.hpp"

#include <cstdint>
#include <cstdio>

using trimkit::parallel::SlotWord;

namespace {

constexpr std::uint32_t EPOCHS = 24;  // more than any model's publishes and forks
constexpr std::uint64_t ACTIVE = 8;   // more than any model's threads

SlotWord word(std::uint32_t epoch, bool open, std::uint64_t active) {
    return SlotWord{(std::uint64_t{epoch} << 32) | (open ? SlotWord::OPEN : 0) | active};
}

void print(SlotWord w) {
    std::printf("W(%u, %s, %llu)", w.epoch(), w.open() ? "TRUE" : "FALSE", static_cast<unsigned long long>(w.active()));
}

// `name` as a TLA+ function over the words `allowed` admits
template <typename Allowed, typename Step>
void table(const char* name, Allowed allowed, Step step) {
    std::printf("%sT ==\n", name);
    const char* join = "    ";
    for (std::uint32_t epoch = 0; epoch < EPOCHS; epoch++) {
        for (const bool open : {false, true}) {
            for (std::uint64_t active = 0; active < ACTIVE; active++) {
                const SlotWord w = word(epoch, open, active);
                if (!allowed(w)) {
                    continue;
                }
                std::printf("%s(", join);
                print(w);
                std::printf(" :> ");
                step(w);
                std::printf(")\n");
                join = "    @@ ";
            }
        }
    }
    std::printf("%s(w) == %sT[w]\n\n", name, name);
}

}  // namespace

int main() {
    std::printf(
        "---- MODULE SlotWordTable ----\n"
        "\\* Generated by check/verify/tla/slot_word_table.cpp from src/parallel.hpp's SlotWord.\n"
        "\\* Each transition only over the words its precondition allows.\n"
        "EXTENDS Naturals, TLC\n\n"
        "W(e, o, a) == [epoch |-> e, open |-> o, active |-> a]\n\n");
    const auto any = [](SlotWord) { return true; };
    table("IsFree", any, [](SlotWord w) { std::printf(w.free() ? "TRUE" : "FALSE"); });
    // try_publish: a free word, and one epoch short of the table's end
    table("Reserved", [](SlotWord w) { return w.free() && w.epoch() + 1 < EPOCHS; },
          [](SlotWord w) { print(w.reserved()); });
    table("Opened", [](SlotWord w) { return !w.open() && w.active() == 1; }, [](SlotWord w) { print(w.opened()); });
    table("Joined", [](SlotWord w) { return w.open() && w.active() >= 1 && w.active() + 1 < ACTIVE; },
          [](SlotWord w) { print(w.joined()); });
    table("Left", [](SlotWord w) { return w.active() >= (w.open() ? 2 : 1); }, [](SlotWord w) { print(w.left()); });
    table("Closed", [](SlotWord w) { return w.open() && w.active() >= 1; }, [](SlotWord w) { print(w.closed()); });
    // child_after_fork's, on any word, one epoch short of the table's end
    const auto forkable = [](SlotWord w) { return w.epoch() + 1 < EPOCHS; };
    table("FreedByFork", forkable, [](SlotWord w) { print(w.freed_by_fork()); });
    table("ReopenedByFork", forkable, [](SlotWord w) { print(w.reopened_by_fork()); });
    table("KeptByFork", forkable, [](SlotWord w) { print(w.kept_by_fork()); });
    std::printf("====\n");
    return 0;
}
